import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { middlewareMode: true }, appType: 'custom' });
try {
  const { getWindForecastMapPrediction: predict } = await server.ssrLoadModule('/src/domain/windForecastMap.ts');
  const { predictSavedWindVoyage } = await server.ssrLoadModule('/src/domain/windVoyagePrediction.ts');
  const { createCoalVoyageNavigation } = await server.ssrLoadModule('/src/domain/coalVoyage.ts');
  const { createContractWindForecast } = await server.ssrLoadModule('/src/domain/contractWindForecast.ts');
  const { getWindForecastIssueTime } = await server.ssrLoadModule('/src/domain/windForecast.ts');
  const { routes } = await server.ssrLoadModule('/src/data/routes.ts');
  const { GAME_TIME_MULTIPLIER } = await server.ssrLoadModule('/src/data/gameConstants.ts');
  const route = routes[0], T = getWindForecastIssueTime(Date.UTC(2026, 10, 2));
  const make = () => {
    const ship = { id: 'ship-map-test', name: '予報テスト船', kind: 'powered', cruisingSpeedKnots: 6, maxSpeedKnots: 10, activeContractId: 'accepted-map-test', fuel: { fuelType: 'coal', capacityTons: 100, remainingTons: 100, referenceSpeedKnots: 6, referenceConsumptionTonsPerVoyageHour: 0.2 } };
    const snapshot = createContractWindForecast(route, T);
    for (const rows of Object.values(snapshot.forecastsByHex)) for (const slot of rows) slot.forecastWind = { speedMps: 0, fromDeg: null };
    const contract = { id: ship.activeContractId, routeId: route.id, windForecastSnapshot: snapshot };
    const voyage = { id: 'voyage-map-test', shipId: ship.id, contractId: contract.id, phase: 'sailing', departedRealTime: T, lastProcessedRealTime: T, currentSeaHexIndex: 0, distanceIntoHexNm: 0, fuelNavigation: createCoalVoyageNavigation(ship, route, 1, 6) };
    return { ship, contract, voyage };
  };
  const f = make(), before = JSON.stringify(f);
  const at = predict([f.ship], f.voyage, f.contract, T, 1);
  assert.equal(at.kind, 'ready');
  assert.equal(at.prediction.requestedRealTime, T + 3600000 / GAME_TIME_MULTIPLIER);
  assert.ok(Math.abs(at.prediction.position.distanceTravelledNm - 6) < 1e-6);
  const later = predict([f.ship], f.voyage, f.contract, T, 48);
  assert.equal(later.prediction.positionStatus, 'arrived');
  assert.equal(JSON.stringify(f), before);
  assert.deepEqual(predict([f.ship], f.voyage, f.contract, T, 1), at);
  console.log('PASS time conversion, arrival, repeatability and no state mutation');
  const loading = make();
  loading.voyage.phase = 'loading';
  loading.voyage.departedRealTime = T + 60000;
  assert.equal(predict([loading.ship], loading.voyage, loading.contract, T, 0).prediction.positionStatus, 'notDeparted');
  console.log('PASS loading delay preserves pre-departure position');
  const mid = at.prediction.checkpoint;
  const resumed = make();
  Object.assign(resumed.voyage, { lastProcessedRealTime: mid.processedRealTime, currentSeaHexIndex: mid.legIndex, distanceIntoHexNm: mid.distanceIntoLegNm });
  resumed.ship.fuel.remainingTons = mid.fuelRemaining;
  resumed.voyage.fuelNavigation.fuelConsumedTons = mid.totalFuelUsed;
  const resumedResult = predict([resumed.ship], resumed.voyage, resumed.contract, mid.processedRealTime, 1);
  const direct = predictSavedWindVoyage({ route, snapshot: resumed.contract.windForecastSnapshot, departureRealTime: T, state: mid, selectedSpeedKnots: 6, loadSpeedFactor: 1, referenceFuelPerVoyageHour: 0.2, referenceSpeedKnots: 6 }, mid.processedRealTime + 3600000 / GAME_TIME_MULTIPLIER);
  assert.deepEqual(resumedResult.prediction, direct);
  console.log('PASS current checkpoint and fuel are used together');
  const missing = make();
  delete missing.contract.windForecastSnapshot;
  const unavailable = predict([missing.ship], missing.voyage, missing.contract, T, 1);
  assert.equal(unavailable.prediction.etaRealTime, null);
  assert.equal(unavailable.prediction.position, null);
  const horizon = predict([f.ship], f.voyage, f.contract, f.contract.windForecastSnapshot.validTo + 1, 0);
  assert.equal(horizon.prediction.position, null);
  console.log('PASS missing forecast and uncovered time never invent a marker');
  const depleted = make();
  depleted.ship.fuel.remainingTons = 0.001;
  const stop = predict([depleted.ship], depleted.voyage, depleted.contract, T, 1);
  assert.equal(stop.prediction.positionStatus, 'fuelDepleted');
  assert.equal(stop.prediction.etaRealTime, null);
  assert.equal(stop.prediction.checkpoint.fuelRemaining, 0);
  console.log('PASS predicted exhaustion is a stop, not an actual return');
  const bad = make();
  assert.equal(predict([], bad.voyage, bad.contract, T, 0).kind, 'unavailable');
  assert.equal(predict([bad.ship], null, null, T, 0).kind, 'unavailable');
  assert.equal(predict([bad.ship], { ...bad.voyage, contractId: 'other' }, bad.contract, T, 0).kind, 'unavailable');
  assert.equal(predict([bad.ship], { ...bad.voyage, fuelNavigation: undefined }, bad.contract, T, 0).kind, 'unavailable');
  assert.equal(predict([bad.ship], { ...bad.voyage, phase: 'completed' }, bad.contract, T, 0).kind, 'unavailable');
  assert.equal(predict([bad.ship], bad.voyage, bad.contract, T, NaN).kind, 'unavailable');
  assert.equal(predict([bad.ship], bad.voyage, bad.contract, T, 49).kind, 'unavailable');
  console.log('PASS unsupported, mismatched, completed and invalid inputs are explicit');
} finally { await server.close(); }
