import assert from 'node:assert/strict';
import {createServer} from 'vite';
import {fileURLToPath} from 'node:url';
let server;
try {
  server = await createServer({root:fileURLToPath(new URL('../',import.meta.url)),server:{middlewareMode:true},appType:'custom'});
  const load = name => server.ssrLoadModule('/src/'+name+'.ts');
  const {createPlannedVoyageState} = await load('domain/plannedVoyageState');
  const {buildVoyagePlanRoute} = await load('domain/voyagePlanRoute');
  const {initialShip} = await load('data/ships');
  const ship=structuredClone(initialShip);
  const built=buildVoyagePlanRoute({departurePortId:'port_selene',destinationPortId:'port_rigel'}, {stops:[{portId:'port_aldera',refuelTargetPercent:80}],legs:[{waypointHexIds:[]},{waypointHexIds:[]}]});
  assert.equal(built.ok,true);
  const voyage={id:'test-voyage',shipId:ship.id,contractId:'test-contract',phase:'loading',departedRealTime:Date.UTC(2026,10,3)};
  const input={voyage,ship,route:built.route,selectedSpeedKnots:6,loadSpeedFactor:.9};
  const before=JSON.stringify(input);
  const state=createPlannedVoyageState(input);
  assert.equal(state.modelVersion,'planned-voyage-v1');
  assert.equal(state.settings.selectedSpeedKnots,6);
  assert.equal(state.settings.loadSpeedFactor,.9);
  assert.equal(state.settings.fuelCapacityTons,5);
  assert.equal(state.checkpoint.processedRealTime,voyage.departedRealTime);
  assert.equal(state.checkpoint.currentSectionIndex,0);
  assert.equal(state.checkpoint.totalFuelUsedTons,0);
  assert.deepEqual(state.checkpoint.portCalls,[]);
  assert.equal(Object.hasOwn(state.checkpoint,'fuelRemaining'),false);
  assert.equal(JSON.stringify(input),before);
  assert.deepEqual(JSON.parse(JSON.stringify(state)),state);
  input.route.sections[0].hexIds.length=0;
  assert.ok(state.route.sections[0].hexIds.length>0);
  const restored={...input,route:state.route};
  assert.throws(()=>createPlannedVoyageState({...restored,selectedSpeedKnots:8}),RangeError);
  assert.throws(()=>createPlannedVoyageState({...restored,loadSpeedFactor:1.1}),RangeError);
  assert.throws(()=>createPlannedVoyageState({...restored,voyage:{...voyage,shipId:'wrong'}}));
  assert.throws(()=>createPlannedVoyageState({...restored,voyage:{...voyage,phase:'sailing'}}));
  const zero=structuredClone(ship);zero.fuel.remainingTons=0;
  createPlannedVoyageState({...restored,ship:zero});
  assert.equal(zero.fuel.remainingTons,0);
  assert.equal(Object.hasOwn(voyage,'plannedNavigation'),false);
  console.log('Planned voyage state creation assertions passed');
} finally {if(server)await server.close();}
