import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
let server;
try {
  server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { middlewareMode: true }, appType: 'custom' });
  const load = path => server.ssrLoadModule('/src/' + path);
  const { VoyagePlanCalculationPanel } = await load('components/contract/PlannedContractDetailScreen.tsx');
  const { VoyagePlanReviewDetails } = await load('components/contract/VoyagePlanConfirmation.tsx');
  const { createConfirmedPlanReview } = await load('domain/confirmedPlanReview.ts');
  const { buildVoyagePlanRoute } = await load('domain/voyagePlanRoute.ts');
  const { tutorialWheatContract: contract } = await load('data/contracts.ts');
  const { initialShip } = await load('data/ships.ts');
  const { getRouteById } = await load('data/routes.ts');
  const { formatFuelTons, applyFreeRefuel } = await load('domain/freeRefuel.ts');
  const { ceilTo1Minute, formatDateTime } = await load('domain/time.ts');
  const ship = structuredClone(initialShip);
  const endpoints = getRouteById(contract.routeId);
  const built = buildVoyagePlanRoute({ departurePortId: endpoints.fromPortId, destinationPortId: endpoints.toPortId }, { stops: [], legs: [{ waypointHexIds: [] }] });
  assert.equal(built.ok, true);
  const start = Date.UTC(2026, 10, 5), deadline = start + 86400000;
  const before = JSON.stringify({ ship, contract, route: built.route });
  let callbacks = 0;
  const render = (review, speed = review.selectedSpeedKnots, selectedShip = review.ship) => renderToStaticMarkup(createElement(VoyagePlanCalculationPanel, { ship: selectedShip, speed, review, onSpeedChange: () => { callbacks++; }, onRefresh: () => { callbacks++; } }));
  const eco = createConfirmedPlanReview(contract.id, contract, ship, built.route, ship.cruisingSpeedKnots, start, deadline);
  const max = createConfirmedPlanReview(contract.id, contract, ship, built.route, ship.maxSpeedKnots, start, deadline);
  assert.ok(max.prediction.totalVoyageHours < eco.prediction.totalVoyageHours);
  assert.ok(max.prediction.totalRequiredFuelTons > eco.prediction.totalRequiredFuelTons);
  assert.equal(max.prediction.totalDistanceNm, eco.prediction.totalDistanceNm);
  for (const review of [eco, max]) {
    const html = render(review);
    assert.ok(html.includes(`data-plan-eta="${review.prediction.plannedEtaRealTime}"`));
    assert.ok(html.includes(formatFuelTons(review.prediction.totalRequiredFuelTons)));
    assert.ok(html.includes('補油は現在無料です'));
    assert.equal(html.includes('type="range"'), false);
    assert.match(html, /<details><summary>計算の詳細/);
    assert.equal(html.includes('<details open'), false);
    const confirmation = renderToStaticMarkup(createElement(VoyagePlanReviewDetails, { review }));
    assert.ok(confirmation.includes(formatDateTime(ceilTo1Minute(review.prediction.plannedEtaRealTime))));
  }
  assert.match(render(eco), /aria-pressed="true"[^>]*>ECO/);
  assert.match(render(max), /aria-pressed="true"[^>]*>MAX/);
  const poor = { ...ship, fuel: { ...ship.fuel, remainingTons: 0 } };
  const shortage = createConfirmedPlanReview(contract.id, contract, poor, built.route, poor.cruisingSpeedKnots, start, deadline);
  assert.equal(shortage.prediction.hasFuelShortage, true);
  const shortageHtml = render(shortage);
  assert.match(shortageHtml.split('<details>')[0], /role="alert"[^>]*>燃料不足/);
  const refilled = applyFreeRefuel(poor, Math.floor(poor.fuel.capacityTons * 10));
  assert.equal(refilled.refuel.costGold, 0);
  const refilledReview = createConfirmedPlanReview(contract.id, contract, refilled.ship, built.route, ship.cruisingSpeedKnots, start, deadline);
  assert.ok(refilledReview.prediction.finalFuelTons !== null || refilledReview.prediction.hasFuelShortage);
  assert.ok(render(refilledReview).includes('補油は現在無料です'));
  assert.equal(poor.fuel.remainingTons, 0);
  const mismatch = render(eco, max.selectedSpeedKnots);
  assert.equal(mismatch.includes('data-plan-eta='), false);
  assert.ok(mismatch.includes('航路・船・速力・燃料を確認'));
  assert.equal(callbacks, 0);
  assert.equal(JSON.stringify({ ship, contract, route: built.route }), before);
  console.log('Real route/review, ECO/MAX calculation and panel/confirmation rendering integration passed; browser clicks, refuel acceptance and persistence not tested.');
} finally { if (server) await server.close(); }
