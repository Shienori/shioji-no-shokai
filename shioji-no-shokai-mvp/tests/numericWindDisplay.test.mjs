import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';
const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { middlewareMode: true }, appType: 'custom' });
try {
  const { describeNumericWind: describe, getNumericWindRows: rowsAt, WIND_IMPACT_COLORS: colors, NumericWindMarkers, NumericWindTable } = await server.ssrLoadModule('/src/components/map/NumericWindDisplay.tsx');
  const { calculateWindSpeedFactor } = await server.ssrLoadModule('/src/domain/shipPerformance.ts');
  const { createContractWindForecast } = await server.ssrLoadModule('/src/domain/contractWindForecast.ts');
  const { getWindForecastIssueTime } = await server.ssrLoadModule('/src/domain/windForecast.ts');
  const { getRouteHexIds } = await server.ssrLoadModule('/src/domain/routePath.ts');
  const { getRouteWindLegs } = await server.ssrLoadModule('/src/domain/routeWind.ts');
  const { routes } = await server.ssrLoadModule('/src/data/routes.ts');
  const tail = describe({ speedMps: 10, fromDeg: 180 }, 0);
  assert.equal(tail.effect, 'positive');
  assert.equal(tail.color, colors.positive);
  assert.equal(tail.deltaLabel, '＋8.00%');
  const head = describe({ speedMps: 10, fromDeg: 0 }, 0);
  assert.equal(head.effect, 'negative');
  assert.equal(head.color, colors.negative);
  assert.equal(head.deltaLabel, '−20.00%');
  const calm = describe({ speedMps: 0, fromDeg: null }, 0);
  assert.equal(calm.color, colors.neutral);
  assert.equal(calm.directionLabel, '風向なし');
  assert.equal(calm.speedLabel, '0.0 m/s');
  assert.equal(calm.deltaLabel, '±0.00%');
  assert.equal(describe({ speedMps: 5.2, fromDeg: 45 }, 0).directionLabel, '北東（45.0°から）');
  console.log('PASS numeric direction, speed and signed impact colors');
  for (const fromDeg of [90, 120]) {
    const row = describe({ speedMps: 10, fromDeg }, 0);
    assert.equal(row.effect, 'negative');
    assert.equal(row.factor, calculateWindSpeedFactor(0, { speedMps: 10, fromDeg }));
  }
  assert.equal(describe({ speedMps: 10, fromDeg: 0 }, 180).effect, 'positive');
  const unevaluated = describe({ speedMps: 10, fromDeg: 180 }, 0, false);
  assert.equal(unevaluated.color, colors.neutral);
  assert.equal(unevaluated.deltaLabel, '補正未評価');
  assert.equal(unevaluated.factor, null);
  assert.throws(() => describe({ speedMps: -1, fromDeg: 0 }, 0));
  console.log('PASS cross and oblique winds use net speed effect; reverse heading and unassessed states');
  const T = getWindForecastIssueTime(Date.UTC(2026, 10, 2)), route = routes[0];
  const snapshot = createContractWindForecast(route, T);
  const ids = getRouteHexIds(route.fromPortId, route.toPortId), legs = getRouteWindLegs(route);
  for (const leg of legs) for (const slot of snapshot.forecastsByHex[leg.hexId]) slot.forecastWind = { speedMps: 10, fromDeg: (leg.headingDeg + 180) % 360 };
  const before = JSON.stringify(snapshot);
  const rows = rowsAt(snapshot, ids, T);
  assert.equal(rows.length, legs.length);
  assert.ok(rows.every(row => row.effect === 'positive'));
  assert.ok(rowsAt(snapshot, ids, T, false).every(row => row.effect === 'neutral'));
  assert.deepEqual(rowsAt(snapshot, ids, snapshot.validTo), []);
  assert.deepEqual(rowsAt(null, ids, T), []);
  assert.equal(JSON.stringify(snapshot), before);
  console.log('PASS route headings and selected-time saved forecasts; no invented out-of-range wind');
  const table = renderToStaticMarkup(createElement(NumericWindTable, { rows }));
  const markers = renderToStaticMarkup(createElement('svg', null, createElement(NumericWindMarkers, { rows })));
  assert.ok(table.includes('風向'));
  assert.ok(table.includes('風速'));
  assert.ok(table.includes('＋8.00%'));
  assert.ok(table.includes(colors.positive));
  assert.ok(markers.includes('10.0 m/s'));
  assert.ok(markers.includes(colors.positive));
  const redRows = [{ ...rows[0], ...head, wind: { speedMps: 10, fromDeg: 0 } }];
  assert.ok(renderToStaticMarkup(createElement(NumericWindTable, { rows: redRows })).includes(colors.negative));
  assert.ok(!table.includes('向かい風'));
  assert.ok(!table.includes('追風'));
  assert.ok(!table.includes('無風'));
  assert.equal(JSON.stringify(snapshot), before);
  console.log('PASS rendered numeric wind labels, signed text and green/red colors without old categories');
} finally { await server.close(); }
