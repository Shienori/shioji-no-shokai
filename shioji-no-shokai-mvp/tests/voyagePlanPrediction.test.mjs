import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
let server;
try {
  server = await createServer({root: fileURLToPath(new URL('../', import.meta.url)), server: {middlewareMode: true}, appType: 'custom'});
  const load = path => server.ssrLoadModule('/src/' + path + '.ts');
  const {buildVoyagePlanRoute} = await load('domain/voyagePlanRoute');
  const {createVoyagePlanForecast} = await load('domain/voyagePlanForecast');
  const {predictVoyagePlan} = await load('domain/voyagePlanPrediction');
  const {initialShip} = await load('data/ships');
  const {getRouteWindLegs} = await load('domain/routeWind');
  const {createContractWindForecast} = await load('domain/contractWindForecast');
  const {estimateSavedWindArrival} = await load('domain/windNavigation');
  const baseRealTime = Date.UTC(2026, 10, 3, 0);
  const ship = structuredClone(initialShip);
  const endpoints = {departurePortId: 'port_selene', destinationPortId: 'port_rigel'};
  const make = draft => { const r = buildVoyagePlanRoute(endpoints, draft); assert.equal(r.ok,true,JSON.stringify(r)); return r.route; };
  const route = make({stops: [], legs: [{waypointHexIds: []}]});
  const forecast = createVoyagePlanForecast(route, baseRealTime);
  const input = {route, forecast, ship, selectedSpeedKnots: 6, loadSpeedFactor: 1, baseRealTime, loadingDurationOperationMs: 0};
  const before = JSON.stringify(input);
  const result = predictVoyagePlan(input);
  assert.equal(result.status, 'arrived');
  const legacyRoute = {id: 'baseline-test', fromPortId: endpoints.departurePortId, toPortId: endpoints.destinationPortId, distance: 60, baseVoyageHours: 10};
  const baseline = estimateSavedWindArrival({legs: getRouteWindLegs(legacyRoute), state: {processedRealTime: baseRealTime, legIndex: 0, distanceIntoLegNm: 0, fuelRemaining: ship.fuel.remainingTons, totalFuelUsed: 0}, selectedSpeedKnots: 6, loadSpeedFactor: 1, referenceFuelPerVoyageHour: ship.fuel.referenceConsumptionTonsPerVoyageHour, referenceSpeedKnots: ship.fuel.referenceSpeedKnots}, createContractWindForecast(legacyRoute, baseRealTime));
  assert.equal(result.etaRealTime, baseline.arrivalRealTime);
  assert.equal(result.totalFuelUsedTons, baseline.state.totalFuelUsed);
  assert.equal(JSON.stringify(input), before);
  const loaded = predictVoyagePlan({...input, loadSpeedFactor: .9, loadingDurationOperationMs: 3600000});
  assert.equal(loaded.departureRealTime, baseRealTime + 600000);
  const loadedBaseline = estimateSavedWindArrival({legs: getRouteWindLegs(legacyRoute), state: {processedRealTime: loaded.departureRealTime, legIndex: 0, distanceIntoLegNm: 0, fuelRemaining: ship.fuel.remainingTons, totalFuelUsed: 0}, selectedSpeedKnots: 6, loadSpeedFactor: .9, referenceFuelPerVoyageHour: ship.fuel.referenceConsumptionTonsPerVoyageHour, referenceSpeedKnots: ship.fuel.referenceSpeedKnots}, createContractWindForecast(legacyRoute, baseRealTime));
  assert.equal(loaded.etaRealTime, loadedBaseline.arrivalRealTime);
  const via = make({stops: [{portId: 'port_aldera', refuelTargetPercent: 100}], legs: [{waypointHexIds: []}, {waypointHexIds: []}]});
  const viaInput = {...input, route: via, forecast: createVoyagePlanForecast(via, baseRealTime)};
  const viaResult = predictVoyagePlan(viaInput);
  assert.equal(viaResult.status, 'arrived');
  assert.equal(viaResult.completedSections.length, 2);
  const [a,b] = viaResult.completedSections;
  assert.equal(a.departureAfterRefuelTons, ship.fuel.capacityTons);
  assert.equal(a.arrivalRealTime, b.departureRealTime);
  assert.ok(a.refuelAddedTons > 0);
  assert.ok(Math.abs(b.arrivalFuelTons - (a.departureAfterRefuelTons - b.fuelUsedTons)) < 1e-10);
  const noAdd = structuredClone(via); noAdd.sections[0].refuelTargetPercent = 0;
  const noAddResult = predictVoyagePlan({...viaInput, route: noAdd});
  assert.equal(noAddResult.completedSections[0].refuelAddedTons, 0);
  const emptyShip = structuredClone(ship); emptyShip.fuel.remainingTons = 0;
  const empty = predictVoyagePlan({...input, ship: emptyShip});
  assert.equal(empty.status, 'insufficientFuel'); assert.equal(empty.etaRealTime, null);
  assert.equal(predictVoyagePlan({...input, forecast: null}).status, 'missingForecast');
  assert.equal(predictVoyagePlan({...input, forecast: viaInput.forecast}).status, 'invalidForecast');
  const expired = predictVoyagePlan({...input, loadingDurationOperationMs: (forecast.sections[0].validTo - baseRealTime + 1) * 6});
  assert.equal(expired.status, 'outsideForecast');
  assert.equal(JSON.stringify(input), before);
  console.log('Voyage plan prediction assertions passed');
} finally {if (server) await server.close();}
