import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
let server;
try {
  server = await createServer({root: fileURLToPath(new URL('../', import.meta.url)), server: {middlewareMode: true}, appType: 'custom'});
  const load = name => server.ssrLoadModule('/src/' + name + '.ts');
  const {buildVoyagePlanRoute} = await load('domain/voyagePlanRoute');
  const {predictVoyagePlan, assessPlanFuel, PLAN_VALUE_NOTICE} = await load('domain/voyagePlanPrediction');
  const {initialShip} = await load('data/ships');
  const make = (from,to,stops=[],legs=[{waypointHexIds:[]}]) => {
    const r=buildVoyagePlanRoute({departurePortId:from,destinationPortId:to},{stops,legs});
    assert.equal(r.ok,true,JSON.stringify(r));return r.route;
  };
  const ship=structuredClone(initialShip);
  const route=make('port_aldera','port_rigel');
  const baseRealTime=Date.UTC(2026,10,3);
  const input={route,ship,selectedSpeedKnots:6,baseRealTime,loadingDurationOperationMs:3600000};
  const before=JSON.stringify(input);
  const p=predictVoyagePlan(input);
  const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-9,`${a} != ${b}`);
  assert.equal(p.totalDistanceNm,45);assert.equal(p.totalVoyageHours,7.5);
  assert.equal(p.departureRealTime,baseRealTime+600000);
  assert.equal(p.plannedEtaRealTime,baseRealTime+5100000);
  close(p.totalRequiredFuelTons,1.5);close(p.finalFuelTons,3.5);
  assert.equal(p.notice,PLAN_VALUE_NOTICE);assert.equal(p.hasFuelShortage,false);
  // Legacy weather/load inputs, even throwing getters, are never read.
  const independent={...input};
  Object.defineProperty(independent,'forecast',{get(){throw Error('Weather must not be read');}});
  Object.defineProperty(independent,'loadSpeedFactor',{get(){throw Error('Load slowdown must not be read');}});
  assert.deepEqual(predictVoyagePlan(independent),p);
  const faster=predictVoyagePlan({...input,selectedSpeedKnots:7});
  close(faster.totalVoyageHours,45/7);
  close(faster.totalRequiredFuelTons,.2*(.2+.8*(7/6)**3)*(45/7));
  const R=1.5, delta=1e-8;
  for(const [fuel,expected] of [[R-delta,'insufficient'],[R,'lowReserve'],[R+delta,'lowReserve'],[1.2*R-delta,'lowReserve'],[1.2*R,'sufficient'],[1.2*R+delta,'sufficient']]) assert.equal(assessPlanFuel(fuel,R),expected);
  assert.equal(assessPlanFuel(.3,.1+.2),'lowReserve');
  for(const fuel of [-1,NaN,Infinity]) assert.throws(()=>assessPlanFuel(fuel,R),RangeError);
  const via=make('port_aldera','port_rigel',[{portId:'port_mira',refuelTargetPercent:80}],[{waypointHexIds:[]},{waypointHexIds:[]}]);
  const v=predictVoyagePlan({...input,route:via});
  assert.equal(v.totalDistanceNm,120);close(v.totalRequiredFuelTons,4);
  const [a,b]=v.sections;
  close(a.arrivalFuelTons,2);close(a.refuelAddedTons,2);close(b.startingFuelTons,4);close(v.finalFuelTons,3);
  assert.equal(a.plannedArrivalRealTime,b.plannedDepartureRealTime);
  const low=structuredClone(ship);low.fuel.remainingTons=2;
  const failed=predictVoyagePlan({...input,route:via,ship:low});
  assert.equal(failed.hasFuelShortage,true);
  assert.equal(failed.sections[0].fuelAssessment,'insufficient');
  assert.equal(failed.sections[0].refuelAddedTons,null);
  assert.equal(failed.sections[1].fuelAssessment,'unreachable');
  assert.equal(failed.sections[1].startingFuelTons,null);assert.equal(failed.finalFuelTons,null);
  assert.equal(failed.plannedEtaRealTime,v.plannedEtaRealTime);
  const noRefuel=structuredClone(via);noRefuel.sections[0].refuelTargetPercent=0;
  const n=predictVoyagePlan({...input,route:noRefuel});close(n.sections[0].refuelAddedTons,0);close(n.finalFuelTons,1);
  assert.throws(()=>predictVoyagePlan({...input,selectedSpeedKnots:8}),RangeError);
  const invalid=structuredClone(ship);invalid.fuel.remainingTons=NaN;
  assert.throws(()=>predictVoyagePlan({...input,ship:invalid}),RangeError);
  assert.equal(JSON.stringify(input),before);
  console.log('Issue 51 no-weather plan time, fuel and boundary assertions passed');
} finally {if(server)await server.close();}
