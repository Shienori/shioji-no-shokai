import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';

const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { middlewareMode: true }, appType: 'custom' });
try {
  const { ForecastMap } = await server.ssrLoadModule('/src/components/map/ForecastMap.tsx');
  const { getWindForecastMapPrediction: predict } = await server.ssrLoadModule('/src/domain/windForecastMap.ts');
  const { createCoalVoyageNavigation } = await server.ssrLoadModule('/src/domain/coalVoyage.ts');
  const { createContractWindForecast } = await server.ssrLoadModule('/src/domain/contractWindForecast.ts');
  const { getWindForecastIssueTime } = await server.ssrLoadModule('/src/domain/windForecast.ts');
  const { getPortHexId } = await server.ssrLoadModule('/src/data/hexMap.ts');
  const { routes } = await server.ssrLoadModule('/src/data/routes.ts');
  const { GAME_TIME_MULTIPLIER } = await server.ssrLoadModule('/src/data/gameConstants.ts');
  const route = routes[0], T = getWindForecastIssueTime(Date.UTC(2026, 10, 2));
  const make = () => {
    const ship = { id: 'render-ship', name: '表示検証船', kind: 'powered', cruisingSpeedKnots: 6, maxSpeedKnots: 10, activeContractId: 'render-contract', currentHexId: getPortHexId(route.fromPortId), fuel: { fuelType: 'coal', capacityTons: 100, remainingTons: 100, referenceSpeedKnots: 6, referenceConsumptionTonsPerVoyageHour: 0.2 } };
    const snapshot = createContractWindForecast(route, T);
    for (const rows of Object.values(snapshot.forecastsByHex)) for (const slot of rows) slot.forecastWind = { speedMps: 0, fromDeg: null };
    const contract = { id: ship.activeContractId, routeId: route.id, windForecastSnapshot: snapshot };
    const voyage = { id: 'render-voyage', shipId: ship.id, contractId: contract.id, phase: 'sailing', departedRealTime: T, lastProcessedRealTime: T, currentSeaHexIndex: 0, distanceIntoHexNm: 0, fuelNavigation: createCoalVoyageNavigation(ship, route, 1, 6) };
    return { ships: [ship], voyage, contract, currentRealTime: T + 3600000 / GAME_TIME_MULTIPLIER };
  };
  const render = props => renderToStaticMarkup(createElement(ForecastMap, props));
  const hasMarker = html => html.includes('stroke-dasharray="4 2"');
  const checks = [];
  const props = make(), before = JSON.stringify(props);
  const html = render(props);
  const result = predict(props.ships, props.voyage, props.contract, props.currentRealTime, 0);
  assert.equal(result.kind, 'ready');
  assert.ok(hasMarker(html));
  assert.ok(html.includes('予測：表示検証船'));
  assert.ok(html.includes('表示検証船（現在）'));
  assert.ok(html.includes('航行予測'));
  assert.ok(html.includes('予報の時間バー（航海時間）'));
  assert.ok(html.includes('type="range"'));
  assert.ok(html.includes('指定時刻の予測残燃料'));
  assert.ok(html.includes(result.prediction.checkpoint.fuelRemaining.toFixed(3)));
  checks.push('renders actual and predicted markers distinctly, timeline and predicted fuel');
  const boxes = [...html.matchAll(/viewBox="([^"]+)"/g)].map(match => match[1]);
  assert.equal(boxes.length, 2);
  assert.equal(boxes[0], boxes[1]);
  const { q, r } = result.prediction.position.axial;
  const transform = `translate(${Math.sqrt(3) * 26 * (q + r / 2)} ${-1.5 * 26 * r})`;
  assert.ok(html.includes(transform));
  checks.push('base map and overlay share viewBox and interpolated SVG coordinates');
  const loading = make();
  loading.voyage.phase = 'loading';
  loading.voyage.departedRealTime = T + 60000;
  loading.currentRealTime = T;
  const loadingHtml = render(loading);
  assert.ok(loadingHtml.includes('出港前'));
  assert.ok(hasMarker(loadingHtml));
  checks.push('loading renders a pre-departure marker');
  const arrived = make();
  arrived.currentRealTime = arrived.contract.windForecastSnapshot.validTo + 1;
  const arrivedHtml = render(arrived);
  assert.ok(arrivedHtml.includes('到着予測'));
  assert.ok(hasMarker(arrivedHtml));
  checks.push('arrival within forecast coverage remains visible after the coverage ends');
  const missing = make();
  delete missing.contract.windForecastSnapshot;
  const missingHtml = render(missing);
  assert.ok(missingHtml.includes('保存予報がありません'));
  assert.ok(missingHtml.includes('指定時刻の船位は予測できません'));
  assert.ok(!hasMarker(missingHtml));
  const horizon = make(), validTo = horizon.contract.windForecastSnapshot.validTo;
  horizon.voyage.departedRealTime = validTo - 1000;
  horizon.voyage.lastProcessedRealTime = validTo - 1000;
  horizon.currentRealTime = validTo + 1;
  const horizonHtml = render(horizon);
  assert.ok(horizonHtml.includes('保存予報の期間内に到着を予測できません'));
  assert.ok(!hasMarker(horizonHtml));
  checks.push('missing forecast and unfinished coverage horizon render explanations without a marker');
  const depleted = make();
  depleted.ships[0].fuel.remainingTons = 0.001;
  const depletedBefore = JSON.stringify(depleted);
  const depletedHtml = render(depleted);
  assert.ok(depletedHtml.includes('燃料切れ予測（停止地点）'));
  assert.ok(hasMarker(depletedHtml));
  assert.equal(JSON.stringify(depleted), depletedBefore);
  checks.push('fuel exhaustion renders a stopping marker without changing real fuel or voyage');
  const legacy = make();
  delete legacy.voyage.fuelNavigation;
  const legacyHtml = render(legacy);
  assert.ok(legacyHtml.includes('今回の数値風予測の対象外'));
  assert.ok(!hasMarker(legacyHtml));
  const emptyHtml = render({ ships: [], voyage: null, contract: null, currentRealTime: T });
  assert.ok(emptyHtml.includes('受注後、積込中または航行中'));
  checks.push('legacy and absent voyages render explicit availability messages');
  const broken = make();
  broken.voyage.contractId = 'wrong-contract';
  const brokenHtml = render(broken);
  assert.ok(brokenHtml.includes('船と受注・航海の対応を確認できません'));
  assert.ok(!hasMarker(brokenHtml));
  checks.push('broken references never render a predicted marker');
  assert.equal(JSON.stringify(props), before);
  assert.equal(render(props), html);
  checks.push('repeated rendering is deterministic and leaves all inputs unchanged');
  console.log(JSON.stringify({ result: 'passed', checks, browserInteraction: 'not tested' }, null, 2));
} finally { await server.close(); }
