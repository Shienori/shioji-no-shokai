import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';
const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { middlewareMode: true }, appType: 'custom' });
try {
  const { prepareContractWindPreview: prepare, getContractPreviewMapPrediction: mapAt, formatContractPreviewEta: label } = await server.ssrLoadModule('/src/domain/contractWindPreview.ts');
  const { createContractWindForecast } = await server.ssrLoadModule('/src/domain/contractWindForecast.ts');
  const { getWindForecastIssueTime } = await server.ssrLoadModule('/src/domain/windForecast.ts');
  const { initialShip } = await server.ssrLoadModule('/src/data/ships.ts');
  const { tutorialWheatContract } = await server.ssrLoadModule('/src/data/contracts.ts');
  const { getRouteById } = await server.ssrLoadModule('/src/data/routes.ts');
  const { getCargoForContract } = await server.ssrLoadModule('/src/domain/lotContract.ts');
  const { getHeavyLoadSpeedFactor } = await server.ssrLoadModule('/src/domain/voyage.ts');
  const { predictSavedWindVoyage } = await server.ssrLoadModule('/src/domain/windVoyagePrediction.ts');
  const { GAME_TIME_MULTIPLIER } = await server.ssrLoadModule('/src/data/gameConstants.ts');
  const { UnifiedWindFuelSummary } = await server.ssrLoadModule('/src/components/contract/UnifiedWindFuelSummary.tsx');
  const { ForecastMap } = await server.ssrLoadModule('/src/components/map/ForecastMap.tsx');
  const T = getWindForecastIssueTime(Date.UTC(2026, 10, 2));
  const contract = { ...tutorialWheatContract }, ship = structuredClone(initialShip), route = getRouteById(contract.routeId);
  const snapshot = createContractWindForecast(route, T);
  for (const rows of Object.values(snapshot.forecastsByHex)) for (const slot of rows) slot.forecastWind = { speedMps: 0, fromDeg: null };
  const before = JSON.stringify({ contract, ship, snapshot });
  const preview = prepare(contract, ship, ship.cruisingSpeedKnots, T, snapshot);
  assert.equal(preview.kind, 'ready');
  assert.equal(preview.input.snapshot, snapshot);
  const departure = T + getCargoForContract(contract).loadingTimeMsPerUnit * contract.quantity / GAME_TIME_MULTIPLIER;
  assert.equal(preview.input.departureRealTime, departure);
  assert.equal(preview.input.loadSpeedFactor, getHeavyLoadSpeedFactor(contract, ship));
  assert.equal(preview.prediction.positionStatus, 'notDeparted');
  assert.equal(preview.prediction.checkpoint.fuelRemaining, ship.fuel.remainingTons);
  assert.deepEqual(preview.prediction, predictSavedWindVoyage(preview.input, T));
  console.log('PASS one edition, loading delay, load factor and recorded fuel');
  for (const hours of [0, 1, 5, 48]) {
    const point = mapAt(preview, hours);
    assert.equal(point.kind, 'ready');
    assert.equal(point.snapshot, snapshot);
    assert.equal(point.prediction.etaRealTime, preview.prediction.etaRealTime);
    assert.equal(point.prediction.totalForecastFuelUsed, preview.prediction.totalForecastFuelUsed);
    assert.deepEqual(point.prediction, predictSavedWindVoyage(preview.input, T + hours * 3600000 / GAME_TIME_MULTIPLIER));
  }
  console.log('PASS all timeline positions share confirmation ETA and total fuel');
  const faster = prepare(contract, ship, ship.maxSpeedKnots, T, snapshot);
  assert.equal(faster.kind, 'ready');
  assert.equal(faster.input.snapshot, snapshot);
  assert.equal(faster.input.selectedSpeedKnots, ship.maxSpeedKnots);
  assert.equal(faster.input.departureRealTime, departure);
  assert.deepEqual(mapAt(faster, 1).prediction, predictSavedWindVoyage(faster.input, T + 3600000 / GAME_TIME_MULTIPLIER));
  console.log('PASS speed change updates every view without regenerating forecast');
  const summary = renderToStaticMarkup(createElement(UnifiedWindFuelSummary, { preview }));
  const chart = renderToStaticMarkup(createElement(ForecastMap, { ships: [ship], voyage: null, contract: null, currentRealTime: T, preview }));
  assert.ok(summary.includes(label(preview)));
  assert.ok(chart.includes(label(preview)));
  assert.ok(summary.includes('積込後の出港予定'));
  assert.ok(chart.includes('受注前の閲覧用予報'));
  assert.ok(chart.includes('出港前'));
  const empty = structuredClone(ship);
  empty.fuel.remainingTons = 0;
  const shortage = prepare(contract, empty, empty.cruisingSpeedKnots, T, snapshot);
  assert.equal(shortage.kind, 'ready');
  assert.equal(shortage.prediction.etaRealTime, null);
  assert.equal(label(shortage), '予測不可');
  assert.equal(mapAt(shortage, 1).prediction.forecastIssue, 'insufficientFuel');
  assert.ok(renderToStaticMarkup(createElement(UnifiedWindFuelSummary, { preview: shortage })).includes('石炭不足'));
  console.log('PASS map and summary display the same ETA and shortage is explicit');
  assert.equal(prepare(contract, ship, ship.cruisingSpeedKnots, T, null).kind, 'unavailable');
  assert.equal(prepare(contract, ship, ship.cruisingSpeedKnots, T, { ...snapshot, routeId: 'wrong' }).kind, 'unavailable');
  assert.equal(prepare(contract, ship, ship.cruisingSpeedKnots + 0.5, T, snapshot).kind, 'unavailable');
  assert.equal(prepare(contract, ship, ship.maxSpeedKnots + 1, T, snapshot).kind, 'unavailable');
  assert.equal(prepare(contract, { ...ship, kind: 'sailing' }, ship.cruisingSpeedKnots, T, snapshot).kind, 'unavailable');
  assert.equal(mapAt(preview, NaN).kind, 'unavailable');
  assert.equal(JSON.stringify({ contract, ship, snapshot }), before);
  assert.deepEqual(prepare(contract, ship, ship.cruisingSpeedKnots, T, snapshot), preview);
  console.log('PASS malformed inputs fail closed and repeated preview leaves all data unchanged');
} finally { await server.close(); }
